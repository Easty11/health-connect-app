// Generates src/buildInfo.js — the build fingerprint the app sends in the /sync
// payload's `client` block (Q22 item 1). Run on every bundle via metro.config.js.
//
// FAIL-CLOSED by design (operator ruling 2026-09-21): the output is gitignored
// and there is NO committed fallback. If this step does not run, src/buildInfo.js
// is absent and the bundle fails at import — a loud, unmissable failure — rather
// than shipping a stale or empty fingerprint. So a missing/failed generation can
// never masquerade as a real build. `git describe --always --dirty` is the SHA
// source; `--dirty` flags an uncommitted working tree, and `--always` falls back
// to the abbreviated commit when no tag is reachable.

import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('..', import.meta.url);

let gitSha;
try {
  gitSha = execSync('git describe --always --dirty', {
    cwd: root,
    encoding: 'utf8',
  }).trim();
} catch (err) {
  // No git checkout / git unavailable -> fail hard, no fallback string.
  console.error(
    '[build-info] FATAL: `git describe --always --dirty` failed — buildInfo requires a git checkout.',
    err?.message ?? err,
  );
  process.exit(1);
}
if (!gitSha) {
  console.error('[build-info] FATAL: git describe returned empty — refusing to write a blank fingerprint.');
  process.exit(1);
}

const pkg = JSON.parse(readFileSync(new URL('package.json', root), 'utf8'));
const builtAt = new Date().toISOString();
const appVersion = pkg.version;

const body =
  '// GENERATED by scripts/gen-build-info.mjs — DO NOT EDIT, DO NOT COMMIT (gitignored).\n' +
  '// Regenerated on every bundle via metro.config.js. Missing file = bundle fails (intended).\n' +
  `export const gitSha = ${JSON.stringify(gitSha)};\n` +
  `export const builtAt = ${JSON.stringify(builtAt)};\n` +
  `export const appVersion = ${JSON.stringify(appVersion)};\n`;

writeFileSync(new URL('src/buildInfo.js', root), body);
console.log(`[build-info] ${gitSha} @ ${builtAt} (v${appVersion})`);
